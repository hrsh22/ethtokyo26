import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const result = spawnSync("forge", ["build", "--root", join(root, "contracts")], {
  cwd: root,
  stdio: "inherit",
});
if (result.status !== 0) {
  process.exit(result.status ?? 1);
}

const contracts = ["SpaceAccount", "SpaceFactory", "NamedSpaceFactory", "SpaceNamespace", "EnsPermissionAdapter", "HierarchicalEnsPermissionAdapter", "AccordForwarder", "AccordTestUSDC"];
const entries = contracts.map((name) => {
  const artifact = JSON.parse(
    readFileSync(join(root, "contracts", "out", `${name}.sol`, `${name}.json`), "utf8"),
  );
  return `export const ${name[0].toLowerCase()}${name.slice(1)}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;`;
});
writeFileSync(
  join(root, "packages", "chain", "src", "generated.ts"),
  `// Generated by scripts/generate-chain-abi.mjs. Do not edit.\n${entries.join("\n\n")}\n`,
);
